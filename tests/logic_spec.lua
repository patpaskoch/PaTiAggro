-- PaTiAggro settings and threat value. Run via PaTiAdmin/tools/check.sh.
local wow = require("wow_api")

local function load()
    return wow.loadAddonFile("Logic.lua", {}).Logic
end

describe("Logic.Migrate", function()
    it("creates defaults for a new character", function()
        local db = load().Migrate(nil)
        assert.is_false(db.locked)
        assert.is_false(db.collapsed)
        assert.equal(1, db.scale)
        assert.equal("auto", db.language)
        assert.equal(1, db.schema)
    end)

    it("keeps the 0.1.0 position and lock state", function()
        local db = load().Migrate({ x = -330, y = 12, locked = true })
        assert.equal(-330, db.x)
        assert.equal(12, db.y)
        assert.is_true(db.locked)
        assert.is_nil(db.point) -- read as CENTER by the window, same as 0.1.0
    end)

    it("keeps saved false values", function()
        local db = load().Migrate({ schema = 1, locked = false, collapsed = false, scale = 1.25, language = "deDE" })
        assert.is_false(db.locked)
        assert.equal(1.25, db.scale)
        assert.equal("deDE", db.language)
    end)
end)

describe("Logic.RestoreDefaults", function()
    it("resets settings and keeps the position", function()
        local db = load().RestoreDefaults({ x = 5, y = 6, locked = true, scale = 1.5, collapsed = true })
        assert.is_false(db.locked)
        assert.is_false(db.collapsed)
        assert.equal(1, db.scale)
        assert.equal(5, db.x)
    end)
end)

describe("Logic.ThreatValue", function()
    local never = function() return false end

    it("clamps readable values to 0-100 and turns missing data into 0", function()
        local Logic = load()
        assert.equal(72, Logic.ThreatValue(72, never))
        assert.equal(100, Logic.ThreatValue(130, never))
        assert.equal(0, Logic.ThreatValue(nil, never))
    end)

    it("passes a secret value through without comparing it", function()
        local function trap() error("secret value was compared") end
        local secret = setmetatable({}, { __lt = trap, __le = trap })
        local isSecret = function(value) return rawequal(value, secret) end
        assert.is_true(rawequal(secret, load().ThreatValue(secret, isSecret)))
    end)
end)

describe("Collapse state", function()
    it("a saved collapsed = true stays; Restore Defaults expands (documented) and keeps the position", function()
        local Logic = load()
        local db = Logic.Migrate({ x = 7, collapsed = true })
        assert.is_true(db.collapsed)
        Logic.RestoreDefaults(db)
        assert.is_false(db.collapsed)
        assert.equal(7, db.x)
    end)
end)

describe("Nameplate markers setting", function()
    it("is on for old saves, a saved false stays, Restore Defaults turns it on again", function()
        local Logic = wow.loadAddonFile("Logic.lua", {}).Logic
        assert.is_true(Logic.Migrate({ x = 1, y = 2 }).markPlates)
        assert.is_false(Logic.Migrate({ markPlates = false }).markPlates)
        assert.is_true(Logic.RestoreDefaults({ markPlates = false }).markPlates)
    end)
end)

describe("Window settings (panel opacity)", function()
    it("old saves get 75 %; a saved value stays; Restore Defaults resets it; an old snapWindows is ignored", function()
        local M = load()
        local db = M.Migrate({ x = 12, y = 34 })
        assert.equal(0.75, db.opacity)
        assert.equal(12, db.x)
        db = M.Migrate({ opacity = 0.4, snapWindows = false })
        assert.equal(0.4, db.opacity)
        db = M.RestoreDefaults({ opacity = 0.4, snapWindows = false, bindings = {}, bindingRanks = {}, watch = {} })
        assert.equal(0.75, db.opacity)
    end)
end)

describe("Logic roles", function()
    it("defaults to AUTO and repairs an unknown saved role", function()
        assert.equal("AUTO", load().Migrate(nil).myRole)
        assert.equal("HEALER", load().Migrate({ myRole = "HEALER" }).myRole)
        assert.equal("AUTO", load().Migrate({ myRole = "BARD" }).myRole)
    end)

    it("uses the chosen role, else the group role, else the tank view", function()
        local Logic = load()
        assert.equal("DAMAGER", Logic.EffectiveRole("DAMAGER", "HEALER"))
        assert.equal("HEALER", Logic.EffectiveRole("AUTO", "HEALER"))
        assert.equal("TANK", Logic.EffectiveRole("AUTO", nil))
        assert.equal("TANK", Logic.EffectiveRole("AUTO", "NONE"))
    end)

    it("without your own role: another member is the tank → your own threat (owner 2026-10-14)", function()
        local Logic = load()
        assert.equal("DAMAGER", Logic.EffectiveRole("AUTO", nil, true))
        assert.equal("TANK", Logic.EffectiveRole("AUTO", nil, false))
        assert.equal("HEALER", Logic.EffectiveRole("AUTO", "HEALER", true))
        assert.equal("TANK", Logic.EffectiveRole("TANK", nil, true))
    end)
end)
